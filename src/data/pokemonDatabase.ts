export const getPokemonById = (id: number): PokemonSpecies | undefined => 
  POKEMON_DATABASE.find(p => p.id === id);

export const getPokemonByName = (name: string): PokemonSpecies | undefined =>
  POKEMON_DATABASE.find(p => p.name.toLowerCase() === name.toLowerCase());

export const getEvolutionChain = (id: number): number[] => {
  const chain: number[] = [];
  let current = getPokemonById(id);
  
  // Go back to base form
  while (current?.evolvesFrom) {
    current = getPokemonById(current.evolvesFrom);
  }
  
  // Build chain forward
  const buildChain = (pkmn: PokemonSpecies | undefined) => {
    if (!pkmn) return;
    chain.push(pkmn.id);
    if (pkmn.evolvesTo) {
      pkmn.evolvesTo.forEach(evoId => {
        buildChain(getPokemonById(evoId));
      });
    }
  };
  
  buildChain(current);
  return [...new Set(chain)];
};

